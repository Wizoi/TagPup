"""Which test reaches which function of tagpup/: the per-test coverage map, generated, kept in tests/coverage_map.txt.xz.

    .venv/Scripts/python.exe tools/test_map.py                        # make the whole map (many minutes; never in the gate)
    .venv/Scripts/python.exe tools/test_map.py --jobs 4
    .venv/Scripts/python.exe tools/test_map.py --files test_x --out <file>   # a trial of a few files, kept elsewhere
    .venv/Scripts/python.exe tools/test_map.py covers tagpup/store/db.py      # the tests that reach a module
    .venv/Scripts/python.exe tools/test_map.py covers tagpup/store/db.py::connect --list
    .venv/Scripts/python.exe tools/test_map.py unique tests.test_x.Case.test_y   # what only that test reaches
    .venv/Scripts/python.exe tools/test_map.py unique test_x                     # what only that file reaches

Each Python test file runs as tools/run_tests.py runs it (its own process and home, the run's corpus, ExifTool's kept
answers, the files that use the checkout one at a time), with tools/covered_unittest.py tracing which function of tagpup/
each test enters: a function, not a line (coverage.py is not in the venv), and only in the test's own process and its
threads; a file that fails runs once more alone when the others have, as run_tests reruns one. A file whose tests start a Python child is marked `children`; one whose process ended before writing is
`unmapped`; tools/affected_tests.py goes back to the imports for both. The page tests reach no Python and are not here.

The map is text, kept xz-compressed (about 2.4 MB of text, 0.2 MB kept; a trial --out not ending .xz is plain text).
It is written whole when every file has run (a run cut off leaves the old map), and only from a clean tagpup/ and
tests/, so it describes the commit it names. tests/test_coverage_map.py fails when the map was edited by hand, or when
tagpup/ or tests/ changed after that commit and HEAD is more than MAX_AGE of commit time later: it is made again by this
tool, at most about once a day, never by hand.

    commit <sha> <its commit time>
    made <when> <wall seconds> <jobs>
    digest <sha256 of every other line>
    file <test file> <ok|failed|unmapped> <children|->
    test <test file> <test id after tests.<file>. , or <shared>: its import and setUpClass> <ok|failed>
    covers <tagpup/x.py::Class.function> <the indexes of the `test` lines that reach it, as ranges: 0-4,9>
"""
import argparse
import concurrent.futures
import hashlib
import json
import lzma
import os
import shutil
import subprocess
import sys
import tempfile
import time

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TOOLS = os.path.join(ROOT, "tools")
sys.path.insert(0, ROOT)

from tagpup.core import processes  # noqa: E402
MAP = os.path.join(ROOT, "tests", "coverage_map.txt.xz")
#: How far HEAD's commit time may run past the map's commit, with tagpup/ or tests/ changed, before the guard fails.
MAX_AGE = 24 * 3600
SHARED = "<shared>"
#: The variable naming the file a test file's process writes what it reached to (tools/covered_unittest.py's OUT).
COVERAGE = "TAGPUP_TEST_COVERAGE"
HEADER = "# Generated by tools/test_map.py; never edit by hand (tests/test_coverage_map.py checks it)."
CAVEAT = ("Coverage says what ran, not what was checked: a test that reaches nothing of its own may still check an "
          "outcome no other test checks (the plan's rule asks for the owner's charter too).")


def _git(*args):
    return processes.run(["git", *args], cwd=ROOT, capture_output=True, text=True, check=True).stdout.strip()


# -- making it ---------------------------------------------------------------------------------------------------

def run_one(module, scratch, run_tests):
    """(module, ok|failed|unmapped, {context: {covered, status, children}}, seconds, its output)."""
    started = time.time()
    home = tempfile.mkdtemp(prefix="tagpup_test_map_")
    out = os.path.join(scratch, module + ".json")
    env = run_tests.file_env(module, home, {COVERAGE: out})
    try:
        done = processes.run([sys.executable, "-m", "unittest", "tools.covered_unittest", "tests." + module], cwd=ROOT,
                             env=env, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, encoding="utf-8",
                             errors="replace")
    finally:
        run_tests.remove(home)
    try:
        with open(out, encoding="utf-8") as handle:
            contexts = json.load(handle)
    except (OSError, ValueError):   # the process ended before unittest did: nothing of it is known
        return module, "unmapped", {}, time.time() - started, done.stdout
    return module, "ok" if done.returncode == 0 else "failed", contexts, time.time() - started, done.stdout


def rerun_alone(result, scratch, run_tests):
    """A file that failed in the pool, run once more alone once the pool has ended, as tools/run_tests.py reruns one;
    its rerun is what the map keeps. The tracer enters a hook at every call: a test that times itself (CPU seconds
    over a loop, a request's cost in microseconds, a share's 0.05 s answer) failed under it on a loaded machine and
    passed alone (2026-11-24: test_derived_batches, test_roots_ingress, test_a_share_asleep)."""
    if result[1] == "ok":
        return result
    print("RERUN   %s alone" % result[0], flush=True)
    again = run_one(result[0], scratch, run_tests)
    print("        %-8s %6.1fs  %s" % (again[1], again[3], again[0]), flush=True)
    return again


def generate(modules, jobs, out):
    """Run `modules` under the tracer, `jobs` at once, and write the map to `out`. Returns the map's lines."""
    sys.path.insert(0, TOOLS)
    import run_tests
    from tests import corpus
    run_tests.kept_answers()
    commit = _git("rev-parse", "HEAD")
    when = int(_git("show", "-s", "--format=%ct", commit))
    if os.path.abspath(out) == MAP:
        dirty = [line for line in _git("status", "--porcelain", "--", "tagpup", "tests").splitlines()
                 if not line.endswith("tests/coverage_map.txt.xz")]
        if dirty:
            raise SystemExit("tagpup/ or tests/ has uncommitted changes (%d); the map describes a commit: commit "
                             "first, or give --out." % len(dirty))
    durations = run_tests.load_durations()
    order = sorted(modules, key=lambda m: -durations.get(m, 1.0))
    shared = [m for m in order if run_tests.uses_the_checkout(m)]
    spread = [m for m in order if m not in shared]
    scratch = tempfile.mkdtemp(prefix="tagpup_test_map_run_")
    started = time.time()
    results = []
    try:
        with corpus.for_run():
            with concurrent.futures.ThreadPoolExecutor(max_workers=max(1, jobs)) as pool:
                def lane():
                    return [run_one(m, scratch, run_tests) for m in shared]
                futures = [pool.submit(lambda m=m: [run_one(m, scratch, run_tests)]) for m in spread]
                for future in concurrent.futures.as_completed(futures + [pool.submit(lane)]):
                    for result in future.result():
                        results.append(result)
                        print("%4d/%d  %-8s %6.1fs  %s" % (len(results), len(modules), result[1], result[3],
                                                         result[0]), flush=True)
            results = [rerun_alone(result, scratch, run_tests) for result in results]
    finally:
        shutil.rmtree(scratch, ignore_errors=True)
    for module, status, _contexts, _seconds, output in sorted(results):
        if status != "ok":   # why it failed, read here: the map keeps only that it did
            print("\n==== %s %s under the tracer, alone:\n%s" % (
                module, status, "\n".join((output or "").splitlines()[-40:])))
    lines = render(results, commit, when, time.time() - started, jobs)
    part = "%s.part-%d" % (out, os.getpid())
    text = ("\n".join(lines) + "\n").encode("utf-8")
    with open(part, "wb") as handle:
        handle.write(lzma.compress(text) if out.endswith(".xz") else text)
    os.replace(part, out)
    return lines


def _ranges(indexes):
    spans, start = [], None
    for i, n in enumerate(indexes):
        if start is None:
            start = n
        if i + 1 == len(indexes) or indexes[i + 1] != n + 1:
            spans.append(str(start) if start == n else "%d-%d" % (start, n))
            start = None
    return ",".join(spans)


def _digest(lines):
    text = "\n".join(line for line in lines if not line.startswith(("digest ", "#")))
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def render(results, commit, when, seconds, jobs):
    """The map's lines from run_one's results."""
    files, tests, covers = [], [], {}
    for module, status, contexts, _seconds, *_output in sorted(results):
        children = any(c.get("children") for c in contexts.values())
        files.append("file %s %s %s" % (module, status, "children" if children else "-"))
        prefix = "tests.%s." % module
        for name in sorted(contexts, key=lambda n: (n != SHARED, n)):
            for key in contexts[name]["covered"]:
                covers.setdefault(key, []).append(len(tests))
            short = name[len(prefix):] if name.startswith(prefix) else name
            tests.append("test %s %s %s" % (module, short, contexts[name]["status"]))
    lines = ["commit %s %d" % (commit, when), "made %s %d %d" % (time.strftime("%Y-%m-%dT%H:%M:%S"), seconds, jobs)]
    lines += files + tests + ["covers %s %s" % (key, _ranges(covers[key])) for key in sorted(covers)]
    return [HEADER, lines[0], lines[1], "digest " + _digest(lines)] + lines[2:]


# -- reading it --------------------------------------------------------------------------------------------------

class Map:
    """The map as read: its commit, its files and tests, and which tests reach each function."""

    def __init__(self, lines):
        self.lines = [line.rstrip("\r\n") for line in lines]
        self.commit, self.when, self.digest = None, 0, None
        self.files, self.tests, self.covers = {}, [], {}
        for line in self.lines:
            kind, _, rest = line.partition(" ")
            if kind == "commit":
                self.commit, when = rest.split()
                self.when = int(when)
            elif kind == "digest":
                self.digest = rest
            elif kind == "file":
                module, status, flags = rest.split()
                self.files[module] = (status, flags)
            elif kind == "test":
                module, name, status = rest.split()
                self.tests.append((module, name, status))
            elif kind == "covers":
                key, spans = rest.split()
                self.covers[key] = [tuple(int(n) for n in s.split("-")) if "-" in s else (int(s), int(s))
                                    for s in spans.split(",")]

    def edited(self):
        """Was it changed after the tool wrote it?"""
        return self.digest != _digest(self.lines)

    def trusted(self, module):
        """Does the map hold all a test file reaches? Not when it failed, wrote nothing, or started a Python child."""
        return self.files.get(module) == ("ok", "-")

    def keys_in(self, relative):
        """The functions of one tagpup/ file that some test reached."""
        return [key for key in self.covers if key.split("::")[0] == relative]

    def reaching(self, keys):
        """{test file: set of test ids, or None for the whole file (its import or setUpClass reaches one)}."""
        found = {}
        for key in keys:
            for low, high in self.covers.get(key, ()):
                for index in range(low, high + 1):
                    module, name, _status = self.tests[index]
                    if name == SHARED:
                        found[module] = None
                    elif found.get(module, ()) is not None:
                        found.setdefault(module, set()).add(name)
        return found

    def unique(self, target):
        """The functions only `target` reaches: a test id (tests.test_x.Case.test_y) or a test file (test_x)."""
        if target.startswith("tests.test_"):
            module, _, name = target[len("tests."):].partition(".")
            mine = {i for i, t in enumerate(self.tests) if t[0] == module and t[1] == name}
        else:
            mine = {i for i, t in enumerate(self.tests) if t[0] == target}
        if not mine:
            raise SystemExit("The map holds no test %s." % target)
        return sorted(key for key, spans in self.covers.items()
                      if all(i in mine for low, high in spans for i in range(low, high + 1)))


def load(path=MAP):
    """The map at `path`, or None when there is none."""
    try:
        with (lzma.open if path.endswith(".xz") else open)(path, "rt", encoding="utf-8") as handle:
            return Map(handle.readlines())
    except FileNotFoundError:
        return None


def stale_reason(found, changed, head_time):
    """Why the map cannot be trusted, or None: `changed` the tagpup/ and tests/ files changed since its commit."""
    if found is None:
        return "there is no map"
    if found.edited():
        return "the map was edited by hand"
    changed = [c for c in changed if c.endswith(".py")]
    if changed and head_time - found.when > MAX_AGE:
        return "%d file(s) of tagpup/ and tests/ changed since the map's commit %s, %.1f days of commits ago" % (
            len(changed), found.commit[:8], (head_time - found.when) / 86400.0)
    return None


def check(path=MAP):
    """stale_reason for the kept map against HEAD, through git; a commit git does not know is a reason too."""
    found = load(path)
    if found is None or found.edited():
        return stale_reason(found, [], 0)
    try:
        changed = _git("diff", "--name-only", found.commit, "HEAD", "--", "tagpup", "tests").split()
    except subprocess.CalledProcessError:
        return "the map's commit %s is not in this history" % found.commit[:8]
    return stale_reason(found, changed, int(_git("show", "-s", "--format=%ct", "HEAD")))


# -- the reports -------------------------------------------------------------------------------------------------

def report_covers(found, target, listing):
    relative, _, name = target.replace("\\", "/").partition("::")   # not a path: of a photo, of a source file
    # A module's body runs in every test that imports it: named only when asked for by name.
    keys = [k for k in found.keys_in(relative) if (k.split("::")[1] == name or k.split("::")[1].startswith(name + "."))
            or not name and not k.endswith("::<module>")]
    if not keys:
        print("No mapped test reaches %s." % target)
        return 1
    reached = found.reaching(keys)
    whole = sorted(m for m, names in reached.items() if names is None)
    print("%s (%d function(s)): %d test file(s), %d by their import or setUpClass" % (
        target, len(keys), len(reached), len(whole)))
    for module in sorted(reached):
        names = reached[module]
        total = sum(1 for t in found.tests if t[0] == module and t[1] != SHARED)
        trust = "" if found.trusted(module) else "  (%s %s: the map may miss some)" % found.files.get(module, ("?", "?"))
        print("  %s: %s%s" % (module, "all %d tests" % total if names is None else "%d of %d tests" % (
            len(names), total), trust))
        if listing and names:
            for test in sorted(names):
                print("      " + test)
    return 0


def report_unique(found, target):
    keys = found.unique(target)
    print("%s: %d function(s) of tagpup/ no other test reaches" % (target, len(keys)))
    for key in keys:
        print("  " + key)
    print(CAVEAT)
    return 0


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--jobs", type=int, default=max(2, (os.cpu_count() or 2) // 2))
    parser.add_argument("--files", nargs="+", help="only these test files (with --out)")
    parser.add_argument("--out", default=MAP, help="where the map goes (default tests/coverage_map.txt.xz)")
    parser.add_argument("--map", default=MAP, help="the map a report reads")
    parser.add_argument("--list", action="store_true", help="covers: name each test, not only the count")
    parser.add_argument("command", nargs="?", choices=("covers", "unique"))
    parser.add_argument("target", nargs="?")
    args = parser.parse_args(argv)
    if args.command:
        found = load(args.map)
        if found is None or not args.target:
            raise SystemExit("A report needs a map (%s) and a target." % args.map)
        reason = stale_reason(found, [], 0)
        if reason:
            print("warning: " + reason)
        return report_covers(found, args.target, args.list) if args.command == "covers" else report_unique(
            found, args.target)
    if args.files and os.path.abspath(args.out) == MAP:
        raise SystemExit("The kept map holds every test file; give --out for a trial of a few.")
    sys.path.insert(0, TOOLS)
    import run_tests
    modules = [m for m in run_tests.test_files(args.files) if not m.endswith(".test.mjs")]
    started = time.time()
    lines = generate(modules, args.jobs, args.out)
    found = Map(lines)
    bad = sorted(m for m in found.files if not found.trusted(m))
    print("%d test file(s), %d tests, %d functions in %.0f s; %d KB; not trusted (failed, unmapped or children): %d" % (
        len(found.files), sum(1 for t in found.tests if t[1] != SHARED), len(found.covers), time.time() - started,
        os.path.getsize(args.out) // 1024, len(bad)))
    for module in bad:
        print("  %s %s %s" % ((module,) + found.files[module]))
    return 0


if __name__ == "__main__":
    sys.exit(main())
